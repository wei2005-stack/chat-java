package com.chat.service;

import com.chat.repo.ChatModelRepository;
import com.chat.repo.MessageRepository;
import com.chat.repo.SessionRepository;
import com.chat.web.ApiException;
import org.springframework.stereotype.Service;

import java.util.ArrayList;
import java.util.List;

/**
 * Chat orchestration ported from the Go use cases: persist the user turn,
 * assemble prompts + context window (+ knowledge excerpts), stream the provider
 * answer and finally persist the assistant turn before the SSE completes.
 */
@Service
public class ChatService {

    private final SessionService sessionService;
    private final SessionRepository sessions;
    private final MessageRepository messages;
    private final ChatModelRepository models;
    private final KnowledgeService knowledge;
    private final ProviderClient provider;

    public ChatService(SessionService sessionService, SessionRepository sessions,
                       MessageRepository messages, ChatModelRepository models,
                       KnowledgeService knowledge, ProviderClient provider) {
        this.sessionService = sessionService;
        this.sessions = sessions;
        this.messages = messages;
        this.models = models;
        this.knowledge = knowledge;
        this.provider = provider;
    }

    /**
     * Normal chat turn. {@code answerId} is generated by the caller so delta
     * events can already carry the assistant message UUID used by the UI.
     */
    public void complete(long userId, String sessionUuid, String chatUuid, String answerId,
                         String prompt, ProviderClient.DeltaSink sink) {
        SessionRepository.ChatSession session = sessionService.getOwned(sessionUuid, userId);
        boolean hasPrompt = messages.hasPrompt(sessionUuid);
        if (!hasPrompt) {
            sessionService.ensurePrompt(sessionUuid, userId, sessionService.defaultSystemPrompt());
        }
        if (prompt != null && !prompt.isBlank()) {
            messages.createMessage(sessionUuid, chatUuid, userId, "user", prompt, "", session.model());
            if (!hasPrompt) {
                String title = firstWords(prompt, 10);
                if (!title.isEmpty()) {
                    sessions.updateTopic(sessionUuid, userId, title);
                }
            }
        }

        ChatModelRepository.ChatModel model = resolveModel(session.model());
        List<ProviderClient.Message> ask = buildMessages(session, sessionUuid,
                Math.max(1, session.maxLength()));
        ProviderClient.Answer answer = provider.stream(model, ask, session.temperature(),
                session.topP(), session.n(), sink);

        messages.createMessage(sessionUuid, answerId, userId, "assistant", answer.content(),
                wrapReasoning(answer.reasoning()), session.model());
    }

    /** Regenerate replaces the existing assistant message identified by chatUuid. */
    public void regenerate(long userId, String sessionUuid, String chatUuid,
                           ProviderClient.DeltaSink sink) {
        SessionRepository.ChatSession session = sessionService.getOwned(sessionUuid, userId);
        ChatModelRepository.ChatModel model = resolveModel(session.model());

        List<ProviderClient.Message> ask = new ArrayList<>();
        for (MessageRepository.Prompt prompt : messages.prompts(sessionUuid)) {
            ask.add(new ProviderClient.Message(prompt.role(), prompt.content()));
        }
        for (MessageRepository.ChatMessage message : messages.messagesBefore(sessionUuid, chatUuid,
                Math.max(1, session.maxLength()))) {
            ask.add(new ProviderClient.Message(message.role(), message.content()));
        }
        ask = augmentWithKnowledge(userId, ask);

        ProviderClient.Answer answer = provider.stream(model, ask, session.temperature(),
                session.topP(), session.n(), sink);
        messages.updateContent(chatUuid, userId, answer.content());
    }

    private List<ProviderClient.Message> buildMessages(SessionRepository.ChatSession session,
                                                       String sessionUuid, int lastN) {
        List<ProviderClient.Message> list = new ArrayList<>();
        for (MessageRepository.Prompt prompt : messages.prompts(sessionUuid)) {
            list.add(new ProviderClient.Message(prompt.role(), prompt.content()));
        }
        for (MessageRepository.ChatMessage message : messages.latestMessages(sessionUuid, lastN)) {
            list.add(new ProviderClient.Message(message.role(), message.content()));
        }
        return augmentWithKnowledge(session.userId(), list);
    }

    /**
     * Prepends the retrieval block when the user has documents. Retrieval errors
     * never block a normal chat request, matching the Go implementation.
     */
    private List<ProviderClient.Message> augmentWithKnowledge(long userId,
                                                              List<ProviderClient.Message> list) {
        String question = lastUserQuestion(list);
        if (question.isEmpty()) {
            return list;
        }
        KnowledgeService.KnowledgeContext context;
        try {
            context = knowledge.buildContext(userId, question);
        } catch (RuntimeException ex) {
            return list;
        }
        if (!context.available()) {
            return list;
        }
        List<ProviderClient.Message> augmented = new ArrayList<>(list.size() + 1);
        augmented.add(new ProviderClient.Message("system", context.text()));
        augmented.addAll(list);
        return augmented;
    }

    private static String lastUserQuestion(List<ProviderClient.Message> list) {
        for (int i = list.size() - 1; i >= 0; i--) {
            ProviderClient.Message message = list.get(i);
            if (!"assistant".equals(message.role()) && message.content() != null
                    && !message.content().isBlank()) {
                return message.content();
            }
        }
        return "";
    }

    private ChatModelRepository.ChatModel resolveModel(String name) {
        ChatModelRepository.ChatModel model = name == null || name.isBlank()
                ? models.findDefault()
                : models.findByName(name);
        if (model == null) {
            model = models.findDefault();
        }
        if (model == null) {
            throw new ApiException(500, "generation_failed", "No enabled chat model is configured");
        }
        return model;
    }

    private static String firstWords(String prompt, int count) {
        String[] words = prompt.trim().split("\\s+");
        int end = Math.min(words.length, count);
        return String.join(" ", java.util.Arrays.copyOf(words, end)).trim();
    }

    private static String wrapReasoning(String reasoning) {
        if (reasoning == null || reasoning.isEmpty()) {
            return "";
        }
        return "<think>\n\n" + reasoning + "\n\n</think>\n\n";
    }
}
